#!/usr/bin/env python
"""R56 figure/table materials from R55 exports.
Read-only source: outputs/r56/data/* main-table npz and R55 markdown tables.
Outputs: outputs/r56/{tables,figures,manifest}. No model training or inference.
"""
from pathlib import Path
import hashlib, json, re
import numpy as np

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'workspace' / 'outputs' / 'r56'
DATA = ROOT / 'workspace' / 'outputs' / 'r55' / 't2_main'
TABLES = OUT / 'tables'; FIGS = OUT / 'figures'
TABLES.mkdir(exist_ok=True); FIGS.mkdir(exist_ok=True)
PARAMS = ['log10 r', 'n_t', 'log10 kappa10', 'log10 T_re', 'DN_re']
PARAM_TEX = [r'$\log_{10}r$', r'$n_\mathrm{t}$', r'$\log_{10}\kappa_{10}$', r'$\log_{10}T_{\rm re}$', r'$\Delta N_{\rm re}$']
SEEDS = [20265921, 11, 22, 33, 44, 55]
W = np.array([34.744, 5.008, 8.963, 8.745, 35.451])
BINS = [('<1', lambda s: s <= 1), ('1--10', lambda s: (s > 1) & (s <= 10)),
        ('10--100', lambda s: (s > 10) & (s <= 100)), ('>100', lambda s: s > 100),
        ('>1', lambda s: s > 1)]

def r2(yhat, y):
    return float(1 - np.sum((y-yhat)**2) / np.sum((y-y.mean())**2))

def load(tier, seed):
    if tier == 'now':
        p = DATA / f'U1c_s1_main_now_noise{seed}_Median5000_plus.npz'
    else:
        p = DATA / f'U1c_fut_s1_main_fut_noise{seed}_Median5000_plus.npz'
    z = np.load(p, allow_pickle=True)
    return p, z

def metrics(z, mask):
    t, pm, q05, q95 = z['true'][:, :5][mask], z['posterior_mean'][:, :5][mask], z['q05'][:, :5][mask], z['q95'][:, :5][mask]
    a=[]
    for i in range(5):
        a.append((float(np.median(q95[:,i]-q05[:,i])/W[i]), float(np.mean((t[:,i]>=q05[:,i])&(t[:,i]<=q95[:,i]))), r2(pm[:,i],t[:,i])))
    return np.array(a)

def get_table(tier):
    zs=[]
    for seed in SEEDS:
        p,z=load(tier,seed); zs.append(z)
    # Check shared IDs and exact sample geometry.
    ids=[str(x) for x in zs[0]['mongo_ids']]
    for z in zs[1:]: assert [str(x) for x in z['mongo_ids']]==ids
    av=zs[0]['real_avail']; snr=zs[0]['snr_combined']
    assert all(np.array_equal(av,z['real_avail']) and np.array_equal(snr,z['snr_combined']) for z in zs[1:])
    out={}
    for label,fn in BINS:
        m=fn(snr); mats=np.stack([metrics(z,m) for z in zs])
        out[label]={'n':int(m.sum()),'mean':mats.mean(0).tolist(),'lo':mats.min(0).tolist(),'hi':mats.max(0).tolist()}
    # Availability subgroups
    groups={'PTA':(av[:,1]==0)&(av[:,2]==0),'PTA+LISA':(av[:,1]==1)&(av[:,2]==0),'all3':av[:,2]==1}
    sub={}
    for gn,gm in groups.items():
        sub[gn]={}
        for label,fn in BINS:
            m=gm&fn(snr); mats=np.stack([metrics(z,m) for z in zs])
            sub[gn][label]={'n':int(m.sum()),'mean':mats.mean(0).tolist(),'lo':mats.min(0).tolist(),'hi':mats.max(0).tolist()}
    return zs[0],out,sub

def cell(x):
    vals=[0.0 if abs(float(v))<0.0005 else float(v) for v in x]
    return f'{vals[0]:.2f}/{vals[1]:.2f}/{vals[2]:+.2f}'
def tex_num(x): return f'{x:.2f}'
def tex_bin(label):
    return {'<1':r'$<1$', '1--10':r'$1$--$10$', '10--100':r'$10$--$100$', '>100':r'$>100$', '>1':r'$>1$ (all)'}[label]
def write_main_tex(tier, data):
    z, rows, sub = data
    name='now' if tier=='now' else 'future'; title='Current' if tier=='now' else 'Future'
    lines=[r'% Auto-generated by R56 figure_materials.py; do not edit sample701.tex.',
           r'% Cell = posterior 5--95 width / W_pop, coverage, R^2; six-noise-seed arithmetic mean.',
           r'\begin{deluxetable*}{lcccccc}',r'\tablecaption{'+title+r' configuration (NANOGrav 15-yr + LISA + LIGO O3 if current; NGmock + LISA + Cosmic Explorer 40 km if future): amortized posterior diagnostics\label{tab:r56_'+name+r'}}',
           r'\tablehead{\colhead{SNR} & \colhead{$n$} & \colhead{$\log_{10}r$} & \colhead{$n_\mathrm{t}$} & \colhead{$\log_{10}\kappa_{10}$} & \colhead{$\log_{10}T_{\rm re}$} & \colhead{$\Delta N_{\rm re}$}}',r'\startdata']
    for label,fn in BINS:
        r=rows[label]['mean']; lines.append(tex_bin(label)+' & '+str(rows[label]['n'])+' & '+' & '.join(cell(x) for x in r)+r' \\')
    lines += [r'\enddata',r'\tablecomments{Each cell reports width divided by the full-population 5--95\% width, empirical 90\% coverage, and $R^2$. The SNR is the square root of the sum of squared band SNRs computed from clean spectra. The table uses 52,115 unique validation IDs, six independent noise realizations (seeds 20265921, 11, 22, 33, 44, 55), and 5,000 posterior samples per realization. The three quantities are averaged across realizations; posterior samples are not pooled.}',r'\end{deluxetable*}','']
    (TABLES/f'r56_table_{name}.tex').write_text('\n'.join(lines),encoding='utf-8')
    # Availability appendix long table.
    lines=[r'\begin{deluxetable*}{lccccccc}',r'\tablecaption{Real-availability appendix for the '+title+r' configuration}',r'\tablehead{\colhead{Availability} & \colhead{SNR} & \colhead{$n$} & \colhead{$\log_{10}r$} & \colhead{$n_\mathrm{t}$} & \colhead{$\log_{10}\kappa_{10}$} & \colhead{$\log_{10}T_{\rm re}$} & \colhead{$\Delta N_{\rm re}$}}',r'\startdata']
    for gn in ['PTA','PTA+LISA','all3']:
        for label,fn in BINS:
            lines.append(gn+' & '+tex_bin(label)+' & '+str(sub[gn][label]['n'])+' & '+' & '.join(cell(x) for x in sub[gn][label]['mean'])+r' \\')
    lines += [r'\enddata',r'\tablecomments{Same metric and six-realization averaging convention as the main table.}',r'\end{deluxetable*}','']
    (TABLES/f'r56_appendix_availability_{name}.tex').write_text('\n'.join(lines),encoding='utf-8')
    # Range appendix.
    lines=[r'\begin{deluxetable*}{llccccc}',r'\tablecaption{Six-realization ranges for the '+title+r' configuration}',r'\tablehead{\colhead{SNR} & \colhead{quantity} & \colhead{$\log_{10}r$} & \colhead{$n_\mathrm{t}$} & \colhead{$\log_{10}\kappa_{10}$} & \colhead{$\log_{10}T_{\rm re}$} & \colhead{$\Delta N_{\rm re}$}}',r'\startdata']
    for label,fn in BINS:
        lines.append(tex_bin(label)+' & width & '+' & '.join(f'{rows[label]["lo"][i][0]:.2f}--{rows[label]["hi"][i][0]:.2f}' for i in range(5))+r' \\')
        lines.append(' & coverage & '+' & '.join(f'{rows[label]["lo"][i][1]:.2f}--{rows[label]["hi"][i][1]:.2f}' for i in range(5))+r' \\')
    lines += [r'\enddata',r'\tablecomments{Ranges are minimum--maximum across six noise realizations; they are not uncertainty intervals on the mean.}',r'\end{deluxetable*}','']
    (TABLES/f'r56_appendix_ranges_{name}.tex').write_text('\n'.join(lines),encoding='utf-8')

def main():
    manifest={'source_files':{},'outputs':[],'configs':{}}
    all_tables={}
    for tier in ('now','future'):
        d=get_table(tier); all_tables[tier]=d; write_main_tex(tier,d)
        for p in DATA.glob(f'*{tier}*npz'):
            manifest['source_files'][p.name]=hashlib.sha256(p.read_bytes()).hexdigest()
    # Save machine-readable aggregate for plotting script and validation.
    serial={}
    for tier,(z,rows,sub) in all_tables.items():
        serial[tier]={'snr':z['snr_combined'].tolist(),'true':z['true'][:,:5].tolist(),'ids':[str(x) for x in z['mongo_ids']], 'real_avail':z['real_avail'].tolist(), 'rows':rows,'sub':sub}
    (OUT/'r56_aggregate.json').write_text(json.dumps(serial),encoding='utf-8'); manifest['outputs']=[str(p.relative_to(OUT)) for p in sorted(TABLES.glob('*.tex'))]
    (OUT/'r56_manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    print('TABLES_DONE',manifest['outputs'])
if __name__=='__main__':main()
